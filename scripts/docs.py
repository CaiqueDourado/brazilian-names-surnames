"""Generate the data dictionaries and the Kaggle metadata from schema/.

schema/columns.json  -> docs/data-dictionary.md, docs/data-dictionary.pt-BR.md
schema/dataset.json  -> data/dataset-metadata.json (read by `kaggle datasets create -p data`)

Usage:  python scripts/docs.py   (run after build.py: examples and null rates come from data/)
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
KAGGLE_TYPES = {"string": "string", "string (list)": "string", "integer": "integer", "float": "number", "boolean": "boolean"}


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def example(series: pd.Series) -> str:
    values = series.dropna()
    if values.empty:
        return ""
    text = str(values.iloc[len(values) // 2])
    text = text if len(text) <= 40 else text[:37] + "…"
    return "`" + text.replace("|", "\\|").replace("`", "'") + "`"


def dictionary(meta: dict, columns: list[dict], tables: dict[str, pd.DataFrame], lang: str) -> str:
    pt = lang == "pt"
    lines = [
        f"# {'Dicionário de dados' if pt else 'Data dictionary'}: {meta['title_pt' if pt else 'title']}",
        "",
        (
            "Gerado por `scripts/docs.py` a partir de `schema/columns.json`. "
            "Tipos, nulos e exemplos vêm dos arquivos em `data/`."
            if pt
            else "Generated by `scripts/docs.py` from `schema/columns.json`. Types, null rates and examples come from the files in `data/`."
        ),
        "",
    ]
    for table in meta["tables"]:
        frame = tables[table["file"]]
        lines += [f"## `{table['file']}`", "", table["description_pt" if pt else "description"], ""]
        lines += [
            ("| Coluna | Tipo | Nulos | Exemplo | Descrição | Padrão | Origem |" if pt
             else "| Column | Type | Null | Example | Description | Standard | Origin |"),
            "|---|---|---|---|---|---|---|",
        ]
        for col in (c for c in columns if c.get("table", meta["tables"][0]["file"]) == table["file"]):
            series = frame[col["name"]]
            null = f"{series.isna().mean() * 100:.1f}%".replace(".", "," if pt else ".")
            desc = col["description_pt" if pt else "description_en"].replace("|", "\\|")
            origin = col["origin"]
            if pt:
                origin = (origin.replace("enrichment", "enriquecimento").replace("corrected", "corrigido")
                      .replace("source", "fonte").replace("derived", "derivado").replace("generated", "gerado"))
            lines.append(f"| `{col['name']}` | {col['type']} | {null} | {example(series)} | {desc} | {col['standard']} | {origin} |")
        lines.append("")
    lines += [
        "## " + ("Convenções" if pt else "Conventions"),
        "",
        *(meta["conventions_pt"] if pt else meta["conventions"]),
        "",
    ]
    return "\n".join(lines)


def kaggle(meta: dict, columns: list[dict]) -> dict:
    resources = []
    for table in meta["tables"]:
        cols = [c for c in columns if c.get("table", meta["tables"][0]["file"]) == table["file"]]
        fields = [{"name": c["name"], "description": c["description_en"], "type": KAGGLE_TYPES[c["type"]]} for c in cols]
        stem = Path(table["file"]).stem
        resources.append({"path": table["file"], "description": table["description"], "schema": {"fields": fields}})
        # Kaggle's usability score asks for column descriptions on every file, not only the CSV.
        resources.append({"path": f"{stem}.parquet", "description": table["description"].rstrip(".") + " (Parquet, typed).",
                          "schema": {"fields": fields}})
        if table.get("json"):
            resources.append({"path": f"{stem}.json", "description": table["description"].rstrip(".") + " (JSON).",
                              "schema": {"fields": fields}})
    for extra in meta.get("extra_resources", []):
        resources.append(extra)
    return {
        "title": meta["kaggle_title"],
        "subtitle": meta["kaggle_subtitle"],
        "description": (ROOT / meta["kaggle_description_file"]).read_text(encoding="utf-8"),
        "id": f"{meta['kaggle_user']}/{meta['slug']}",
        "licenses": [{"name": meta["kaggle_license"]}],
        "keywords": meta["keywords"],
        "resources": resources,
    }


def main() -> None:
    meta = load_json(ROOT / "schema" / "dataset.json")
    columns = load_json(ROOT / "schema" / "columns.json")
    tables = {t["file"]: pd.read_parquet(ROOT / "data" / (Path(t["file"]).stem + ".parquet")) for t in meta["tables"]}
    for table in meta["tables"]:
        present = set(tables[table["file"]].columns)
        columns = [c for c in columns if not (c.get("optional") and c.get("table") == table["file"] and c["name"] not in present)]
        names = [c["name"] for c in columns if c.get("table", meta["tables"][0]["file"]) == table["file"]]
        if names != list(tables[table["file"]].columns):
            raise SystemExit(f"schema/columns.json is out of sync with data/{table['file']}")
    (ROOT / "docs" / "data-dictionary.md").write_text(dictionary(meta, columns, tables, "en"), encoding="utf-8")
    (ROOT / "docs" / "data-dictionary.pt-BR.md").write_text(dictionary(meta, columns, tables, "pt"), encoding="utf-8")
    (ROOT / "data" / "dataset-metadata.json").write_text(
        json.dumps(kaggle(meta, columns), ensure_ascii=True, indent=2) + "\n", encoding="utf-8"
    )
    print("docs/data-dictionary*.md and data/dataset-metadata.json updated")


if __name__ == "__main__":
    main()
